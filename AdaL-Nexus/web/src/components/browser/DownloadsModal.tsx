import React from "react";
import { DownloadIcon, ExternalLinkIcon, FileSpreadsheetIcon, XIcon } from "../Icons";

interface DownloadsModalProps {
  isOpen: boolean;
  onClose: () => void;
  downloadStatus?: { filename: string; state: string; percent?: number } | null;
}

export function DownloadsModal({ isOpen, onClose, downloadStatus }: DownloadsModalProps) {
  if (!isOpen) return null;

  const sampleDownloads = [
    {
      name: "ai_startups.xlsx",
      desc: "Verified AI Startups Research Workbook (Generated by sheet.write)",
      url: "/output/ai_startups.xlsx",
      size: "9.8 KB",
      date: "Generated recently",
    },
    {
      name: "m6-accepted-startups.xlsx",
      desc: "Milestone 6 Acceptance Verified Dataset",
      url: "/output/m6-accepted-startups.xlsx",
      size: "9.8 KB",
      date: "Verified acceptance build",
    },
  ];

  return (
    <div className="modal-overlay" onClick={onClose}>
      <div className="modal-card downloads-modal-card" onClick={(e) => e.stopPropagation()}>
        <div className="modal-header">
          <div className="modal-title-row">
            <DownloadIcon size={20} className="text-glow-purple" />
            <h2 className="modal-title">Downloads &amp; Workbooks</h2>
          </div>
          <button type="button" className="btn-modal-close" onClick={onClose} aria-label="Close">
            <XIcon size={18} />
          </button>
        </div>

        {downloadStatus && (
          <div className="active-download-card">
            <div className="active-download-top">
              <strong>{downloadStatus.filename}</strong>
              <span className={`download-state ${downloadStatus.state}`}>
                {downloadStatus.state}
              </span>
            </div>
            {typeof downloadStatus.percent === "number" && (
              <div className="download-progress-bar-wrap">
                <div
                  className="download-progress-fill"
                  style={{ width: `${Math.round(downloadStatus.percent * 100)}%` }}
                />
              </div>
            )}
          </div>
        )}

        <div className="modal-list-body">
          <h3 className="downloads-section-title">Generated Research Workbooks (.xlsx)</h3>
          <div className="downloads-list">
            {sampleDownloads.map((d) => (
              <div key={d.name} className="download-row-item">
                <div className="download-icon-box">
                  <FileSpreadsheetIcon size={20} className="excel-green-icon" />
                </div>
                <div className="download-text-meta">
                  <span className="download-name">{d.name}</span>
                  <span className="download-desc">{d.desc}</span>
                  <span className="download-sub">{d.size} • {d.date}</span>
                </div>
                <a
                  href={d.url}
                  download
                  className="btn-download-action"
                  title={`Download ${d.name}`}
                >
                  <DownloadIcon size={16} />
                  <span>Download</span>
                </a>
              </div>
            ))}
          </div>
        </div>
      </div>
    </div>
  );
}
